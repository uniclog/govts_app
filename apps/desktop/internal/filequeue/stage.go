package filequeue

import (
	"context"
	"errors"
	"os"
	"path/filepath"
	"strings"
)

func (q *FileQueue) StageCreate() (string, error) {
	q.mu.Lock()
	defer q.mu.Unlock()
	if q.stopped {
		return "", context.Canceled
	}
	q.startLocked()
	if q.stageDir == "" {
		return "", errors.New("file staging storage unavailable")
	}
	if err := os.MkdirAll(q.stageDir, 0700); err != nil {
		return "", err
	}
	f, err := os.CreateTemp(q.stageDir, "staged-*")
	if err != nil {
		return "", err
	}
	defer f.Close()
	return filepath.Base(f.Name()), nil
}

func (q *FileQueue) stagePath(id string) (string, error) {
	// Match the single filename generated by CreateTemp. On Windows, suffixes
	// such as a trailing dot can refer to the same underlying file.
	suffix, ok := strings.CutPrefix(id, "staged-")
	if !ok || suffix == "" || len(id) > 80 || strings.Trim(suffix, "0123456789") != "" {
		return "", errors.New("invalid staged file")
	}
	if q.stageDir == "" {
		return "", errors.New("file staging storage unavailable")
	}
	return filepath.Join(q.stageDir, id), nil
}

func (q *FileQueue) StageWrite(id string, offset int64, data []byte) error {
	path, err := q.stagePath(id)
	if err != nil {
		return err
	}
	q.mu.Lock()
	defer q.mu.Unlock()
	if err := q.checkStageLocked(path); err != nil {
		return err
	}
	f, err := os.OpenFile(path, os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	defer f.Close()
	stat, err := f.Stat()
	if err != nil {
		return err
	}
	if stat.Size() != offset {
		return errors.New("staged offset conflict")
	}
	_, err = f.WriteAt(data, offset)
	return err
}

func (q *FileQueue) StageFinish(id string, task FileTask) (FileTask, error) {
	path, err := q.stagePath(id)
	if err != nil {
		return FileTask{}, err
	}
	task.Path = path
	task.Staged = true
	return q.Add(task)
}

func (q *FileQueue) StageCancel(id string) error {
	path, err := q.stagePath(id)
	if err != nil {
		return err
	}
	q.mu.Lock()
	defer q.mu.Unlock()
	if err := q.checkStageLocked(path); err != nil {
		return err
	}
	return os.Remove(path)
}

func (q *FileQueue) checkStageLocked(path string) error {
	if q.stopped {
		return context.Canceled
	}
	q.startLocked()
	for _, task := range q.tasks {
		if task.Staged && task.Path == path {
			return errors.New("staged file belongs to an existing transfer")
		}
	}
	return nil
}
